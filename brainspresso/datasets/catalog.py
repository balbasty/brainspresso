def load(name: str):
    """
    Load the dataset of a catalog entry.

    Parameters
    ----------
    name : str
        Command name (e.g. "ixi")

    Returns
    -------
    Dataset

    Raises
    ------
    KeyError
        If the name is not in the catalog
    """
    from brainspresso.datasets.base import (  # noqa: PLC0415
        Dataset,  # lazy: startup time (`bx --help`)
    )
    path, _ = CATALOG[name]
    module, _, attr = path.partition(":")
    obj = getattr(import_module(module), attr)
    if isinstance(obj, type):
        obj = obj()
    elif not isinstance(obj, Dataset):
        obj = obj(name)
    if obj.name != name:
        raise ValueError(f"Catalog entry {name!r} loads dataset "
                         f"{obj.name!r}")
    return obj
